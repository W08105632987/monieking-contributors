"""MonieKing branded result sheet (free download). Built from the decrypted
lookup result — never forwards Techhub's own PDF, so it carries our branding
only and none of Techhub's."""
import io
from datetime import datetime
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.lib.utils import ImageReader
from reportlab.platypus import HRFlowable, Image, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.verification.normalize import mask_id

_NAVY = colors.HexColor("#12233d")
_GREY = colors.HexColor("#5a5a5a")
_LIGHT = colors.HexColor("#f4f1ea")
_LOGO = Path(__file__).parent / "assets" / "logo.png"

DISCLAIMERS = {
    "nin": "This is a MonieKing verification sheet. It is not an official NIMC document.",
    "bvn": "This is a MonieKing verification sheet. It is not an official bank or NIBSS document.",
}
TITLES = {"nin": "NIN Verification Sheet", "bvn": "BVN Verification Sheet"}


def full_name(data: dict) -> str:
    parts = [data.get("first_name"), data.get("middle_name"), data.get("last_name")]
    return " ".join(str(p).strip() for p in parts if p and str(p).strip()).title()


def build_sheet_pdf(*, kind: str, data: dict, photo_jpeg: bytes | None, reference: str,
                    verified_at: datetime, reveal_id: bool = False) -> bytes:
    st = getSampleStyleSheet()
    st.add(ParagraphStyle(name="T", fontName="Helvetica-Bold", fontSize=17, textColor=_NAVY, spaceAfter=2))
    st.add(ParagraphStyle(name="S", fontName="Helvetica", fontSize=9.5, textColor=_GREY, spaceAfter=8))
    st.add(ParagraphStyle(name="C", fontName="Helvetica", fontSize=10, leading=13))
    st.add(ParagraphStyle(name="CB", fontName="Helvetica-Bold", fontSize=9.5, leading=13, textColor=_GREY))
    st.add(ParagraphStyle(name="N", fontName="Helvetica-Bold", fontSize=15, textColor=_NAVY, leading=18))
    st.add(ParagraphStyle(name="F", fontName="Helvetica-Oblique", fontSize=8, textColor=_GREY, spaceBefore=14, leading=11))

    id_key = "nin" if kind == "nin" else "bvn"
    raw_id = str(data.get(id_key) or "")
    shown_id = raw_id if reveal_id else mask_id(raw_id)

    def P(text, style="C"):
        from xml.sax.saxutils import escape
        return Paragraph(escape(str(text or "—")), st[style])

    story = []
    if _LOGO.exists():
        w, h = ImageReader(str(_LOGO)).getSize()
        story.append(Image(str(_LOGO), width=4.2 * cm, height=4.2 * cm * h / w))
        story.append(Spacer(1, 6))
    story.append(Paragraph(TITLES[kind], st["T"]))
    story.append(Paragraph(DISCLAIMERS[kind], st["S"]))
    story.append(HRFlowable(width="100%", thickness=0.8, color=_NAVY, spaceAfter=10))

    rows = [
        [P("Full name", "CB"), P(full_name(data), "N")],
        [P(f"{id_key.upper()}", "CB"), P(shown_id)],
        [P("Gender", "CB"), P(str(data.get("gender") or "").title())],
        [P("Date of birth", "CB"), P(data.get("date_of_birth"))],
        [P("Phone", "CB"), P(data.get("phone_number"))],
        [P("Address", "CB"), P(data.get("address"))],
        [P("Verified", "CB"), P(verified_at.strftime("%d %b %Y, %H:%M UTC"))],
        [P("Reference", "CB"), P(reference)],
    ]
    details = Table(rows, colWidths=[3.2 * cm, 9.3 * cm])
    details.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("ROWBACKGROUNDS", (0, 0), (-1, -1), [colors.white, _LIGHT]),
    ]))

    if photo_jpeg:
        from PIL import Image as PILImage
        pw, ph = PILImage.open(io.BytesIO(photo_jpeg)).size
        pic = Image(io.BytesIO(photo_jpeg), width=3.2 * cm, height=3.2 * cm * ph / pw)
        layout = Table([[details, pic]], colWidths=[12.7 * cm, 3.6 * cm])
        layout.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP")]))
        story.append(layout)
    else:
        story.append(details)

    story.append(Paragraph(
        "Generated by MonieKing. This sheet reflects a check run at the time shown and is not a certified record. "
        "Keep it private: it contains personal information.", st["F"]))

    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm, topMargin=2 * cm,
                      bottomMargin=2 * cm, title=TITLES[kind]).build(story)
    return buf.getvalue()
